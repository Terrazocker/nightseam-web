"""Bake core/ to content-hashed URLs for both shells.

The core is authored once in core/*.js and copied to
  web/core/<hash>/            (served by the static web host)
  static/js/core/<hash>/      (bundled into the desktop exe via static/)
plus a stable entry stub in each tree (web/core.js, static/js/core.js) whose
explicit export list is derived from core/index.js. A core change therefore
produces new URLs; the stub's cache token must be bumped by hand and is
enforced by scripts/check_core.py.

Byte identity is line-ending normalized (core.autocrlf=true on Windows), so a
CRLF checkout and an LF checkout hash the same.

Usage: python scripts/build_core.py
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core"
MANIFEST = CORE / "core.manifest.json"
WEB_DIR = ROOT / "web"
STATIC_JS = ROOT / "static" / "js"
STUB_NAME = "core.js"


def normalize(data: bytes) -> bytes:
    """Line-ending normalization for hashing and baking (CRLF -> LF)."""
    return data.replace(b"\r\n", b"\n")


def core_root(root: Path | None = None) -> Path:
    return CORE if root is None else Path(root)


def core_files(root: Path | None = None) -> list[Path]:
    base = core_root(root)
    return sorted(p for p in base.rglob("*.js") if p.is_file())


def tree_hash(root: Path | None = None) -> tuple[str, dict[str, str]]:
    """Stable 16-hex tree hash + per-file sha256 (line-ending normalized)."""
    base = core_root(root)
    digest = hashlib.sha256()
    files: dict[str, str] = {}
    for p in core_files(base):
        rel = p.relative_to(base).as_posix()
        one = hashlib.sha256(normalize(p.read_bytes())).hexdigest()
        files[rel] = one
        digest.update(rel.encode("utf-8") + b"\0" + one.encode("ascii") + b"\n")
    return digest.hexdigest()[:16], files


def export_names(index_text: str) -> list[str]:
    """Explicit export list from core/index.js (the stub mirrors it)."""
    match = re.search(r"export\s*\{([^}]+)\}", index_text)
    if not match:
        return []
    names = []
    for part in match.group(1).split(","):
        piece = part.strip().split(" as ")
        if piece and piece[-1].strip():
            names.append(piece[-1].strip())
    return names


def stub_text(hash_: str, names: list[str]) -> str:
    return ("// GENERATED by scripts/build_core.py - do not edit.\n"
            f"export {{ {', '.join(names)} }} from './core/{hash_}/index.js';\n")


def main() -> int:
    if not CORE.is_dir():
        print("build_core: core/ is missing")
        return 1
    hash_, files = tree_hash()
    token = 1
    if MANIFEST.is_file():
        try:
            old = json.loads(MANIFEST.read_text(encoding="utf-8"))
            token = int(old.get("token", 1))
            if old.get("hash") and old["hash"] != hash_:
                token += 1
        except (OSError, ValueError):
            pass
    names = export_names((CORE / "index.js").read_text(encoding="utf-8"))
    if not names:
        print("build_core: core/index.js has no explicit export list")
        return 1
    for dest_root in (WEB_DIR / "core", STATIC_JS / "core"):
        if dest_root.is_dir():
            for child in dest_root.iterdir():
                if child.is_dir():
                    shutil.rmtree(child)
        dest = dest_root / hash_
        for p in core_files():
            target = dest / p.relative_to(CORE)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(normalize(p.read_bytes()))
    (WEB_DIR / STUB_NAME).write_text(stub_text(hash_, names),
                                     encoding="utf-8", newline="\n")
    (STATIC_JS / STUB_NAME).write_text(stub_text(hash_, names),
                                       encoding="utf-8", newline="\n")
    MANIFEST.write_text(
        json.dumps({"hash": hash_, "token": token, "files": files}, indent=2) + "\n",
        encoding="utf-8", newline="\n")
    print(f"build_core: hash={hash_} token={token} files={len(files)} "
          f"-> web/core/{hash_} + static/js/core/{hash_}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
