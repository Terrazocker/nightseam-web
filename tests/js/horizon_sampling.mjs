import assert from 'node:assert/strict';
import * as H from '../../core/horizon.js';
const pano = (extra = {}) => ({paintMode:'obstacle',fov:45,azOffset:0,altBottom:0,altTop:60,...extra});
const mask = () => new Uint8Array(720*360);
const band = (m,c,a,b) => {for(let r=a;r<=b;r++)m[r*720+c]=255;};
const attach = (p,m) => {const {prof,top}=H.profileFromMask(p,m);return {...p,profile:prof,profileTop:top};};
let m=mask();band(m,3,100,100);let p=attach(pano(),m);
assert.equal(p.profile[0],H.altOf(p,100),'single narrow obstruction survives');
band(m,6,40,40);p=attach(pano(),m);assert.equal(p.profile[0],H.altOf(p,40),'highest overlapping obstacle wins');
assert.equal(p.profile[1],H.NO_BLOCK,'adjacent empty bin remains clear');
m=mask();band(m,1,20,20);p=attach(pano({fov:360}),m);
assert.equal(p.profile[0],H.NO_BLOCK,'exact boundary excludes adjacent column');
assert.equal(p.profile[1],H.altOf(p,20));
m=mask();band(m,0,100,100);band(m,719,20,20);
p=attach(pano({fov:360,azOffset:.25}),m);
assert.equal(p.profile[0],H.altOf(p,20),'fractional full seam includes both photo ends');
p=attach(pano({fov:45,azOffset:359.75}),m);
assert.equal(p.profile[719],H.altOf(p,100),'partial start uses near edge');
assert.equal(p.profile[90],H.NO_BLOCK,'partial coverage does not wrap across gap');
p=attach(pano(),m);assert.equal(H.ceilFor(p,45).ceil,H.altOf(p,20),'inclusive right endpoint retained');
assert.equal(H.ceilFor(p,45.01).ceil,H.NO_BLOCK);
m=mask();for(let c=0;c<8;c++)band(m,c,60+c,260-c);
p=attach(pano({paintMode:'sky',blockAbove:true}),m);
assert.equal(p.profile[0],H.altOf(p,253),'sky lower edges intersect');
assert.equal(p.profileTop[0],H.altOf(p,67),'sky upper edges intersect');
assert.equal(H.ceilFor(p,.1).ceilTop,p.profileTop[0]);
assert.equal(H.ceilFor({...p,blockAbove:false},.1).ceilTop,null,'default stays open above');
for(let r=0;r<360;r++)m[r*720+3]=0;
p=attach(pano({paintMode:'sky'}),m);assert.equal(p.profile[0],90,'unpainted overlapping sky column blocks');
m=mask();for(let c=0;c<8;c++)band(m,c,c<4?60:220,c<4?100:260);
p=attach(pano({paintMode:'sky',blockAbove:true}),m);assert.equal(p.profile[0],90,'disjoint capped sky bands block');
p=attach(pano({paintMode:'sky',blockAbove:false}),m);
assert.equal(p.profile[0],H.altOf(p,100),'disjoint default bands remain open above highest lower edge');
assert.equal(H.ceilFor(p,.1).ceilTop,null);
m=mask();for(let c=0;c<8;c++)band(m,c,10,260);
p=attach(pano({paintMode:'sky',blockAbove:true}),m);assert.equal(p.profileTop[0],90.5,'near-photo-top open sentinel retained');
for(let r=0;r<360;r++)m[r*720+3]=0;
band(m,3,80,260);p=attach(pano({paintMode:'sky',blockAbove:true}),m);
assert.equal(p.profileTop[0],H.altOf(p,80),'finite overhang wins over neighboring open-top sentinel');
m=mask();band(m,0,80,260);
p=attach(pano({paintMode:'sky',fov:360,azOffset:.25}),m);
assert.equal(p.profile[0],90,'fractional seam sky bin includes its unpainted photo end');
band(m,719,100,240);p=attach(pano({paintMode:'sky',fov:360,azOffset:.25,blockAbove:true}),m);
assert.equal(p.profile[0],H.altOf(p,240),'fractional seam intersects both lower sky edges');
assert.equal(p.profileTop[0],H.altOf(p,100),'fractional seam intersects both upper sky edges');
const trace={m:'trace',points:[[3.1,100.9],[3.8,100.9]]};
m=H.rebuildMask([trace]);assert.equal(m[100*720+3],255,'sub-column trace survives with upward altitude rounding');
p=attach(pano(),m);assert.ok(p.profile[0]>=H.altOf(p,100.9));
assert.ok(p.profile[0]-H.altOf(p,100.9)<60/359,'rounding error less than one calibrated row');
m=H.rebuildMask([{m:'trace',points:[[0,200],[.9,40],[1.8,200]]}]);
assert.equal(m[40*720],255,'peak inside cell sets highest edge');
m=H.rebuildMask([trace,{m:'e',x:3,y:100,r:1}]);assert.equal(m[100*720+3],0,'later eraser remains authoritative');
const stored=pano({strokes:[],profile:Array(720).fill(23),profileTop:Array(720).fill(-90)});
H.computeProfile(stored);assert.equal(stored.profile[0],23,'absent strokes preserve authoritative profile');
console.log('Conservative horizon sampling, sky intersections and skyline cell boundaries passed');
